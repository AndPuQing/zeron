#!/usr/bin/env python3
"""Write the Files gallery's synthetic project. Never read a user's checkout."""
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "ui/demos/files_snapshot.luau"


def quoted(text):
    eq = ""
    while f"]{eq}]" in text:
        eq += "="
    return f"[{eq}[\n{text}]{eq}]"


def main():
    texts = {
        "README.md": "# Sample project\n\nA small application for exploring the Files panel.\n",
        "Cargo.toml": '[package]\nname = "sample"\nversion = "0.1.0"\nedition = "2024"\n',
        "src/main.rs": 'fn main() {\n    println!("Hello from the sample project");\n}\n',
        "src/settings.rs": "pub struct Settings {\n    pub theme: String,\n}\n",
        "ui/app.luau": 'return ui.text { "Hello, world" }\n',
        "ui/theme.json": '{"background": "#202020", "foreground": "#f0f0f0"}\n',
        ".gitignore": "target/\n",
    }
    texts["src/catalog.rs"] = "// Sample data for scrolling a long file.\n" + "\n".join(
        f'pub const ITEM_{i}: &str = "Sample {i}";' for i in range(600)
    ) + "\n"
    rows = [f"{path}\t{len(text.encode())}\t" for path, text in sorted(texts.items())]
    contents = '\n'.join(f'\t\t["{path}"] = {quoted(text)},' for path, text in sorted(texts.items()))
    OUT.write_text('-- Synthetic gallery project, generated by tools/files_snapshot.py.\n'
                   'return {\n\troot = "~/projects/sample",\n\tname = "sample",\n'
                   f'\tfiles = {quoted(chr(10).join(rows))},\n\timages = {{}},\n'
                   f'\ttexts = {{\n{contents}\n\t}},\n}}\n')


if __name__ == "__main__":
    main()
